/**
 * Normalizes a country code to 2-letter ISO 3166-1 alpha-2, uppercase. Accepts either
 * a 2-letter or 3-letter code; returns null for anything else (or unknown alpha-3s).
 */
export function normalizeCountryCode(code?: string | null): string | null {
  if (!code) return null
  const trimmed = String(code).trim().toUpperCase()
  if (trimmed.length === 2) return trimmed
  if (trimmed.length === 3) return alpha3ToAlpha2[trimmed] || null
  return null
}
